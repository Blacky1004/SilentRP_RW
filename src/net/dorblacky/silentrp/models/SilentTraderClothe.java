package net.dorblacky.silentrp.models;

public class SilentTraderClothe {
    private int id;
    private int trader_id;
    private int clothe_id;
    private int color_id;

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public int getTrader_id() {
        return trader_id;
    }

    public void setTrader_id(int trader_id) {
        this.trader_id = trader_id;
    }

    public int getClothe_id() {
        return clothe_id;
    }

    public void setClothe_id(int clothe_id) {
        this.clothe_id = clothe_id;
    }

    public int getColor_id() {
        return color_id;
    }

    public void setColor_id(int color_id) {
        this.color_id = color_id;
    }
}
